import { expect, test } from '@playwright/test'
import { randomBytes, randomUUID } from 'node:crypto'

test('real local SMTP and API: register, verify, configure agent, review scenario, deep-link refresh, logout',async({page,request,browser})=>{
  test.skip(process.env.LIVE_BACKEND!=='1','Requires an explicitly running local PostgreSQL/Redis/SMTP/API stack; no provider inference is faked.')
  test.setTimeout(90000)
  const errors: string[]=[]
  page.on('pageerror',error=>errors.push(error.message))
  const suffix=randomUUID()
  const email=`browser-${suffix}@example.test`
  const password=randomBytes(24).toString('base64url')
  const mail=process.env.SMOKE_MAIL_URL || 'http://127.0.0.1:58025'
  await page.goto('/register')
  await page.getByRole('textbox',{name:'Full name'}).fill('Browser Tester')
  await page.getByRole('textbox',{name:'Email address'}).fill(email)
  await page.getByLabel('Password',{exact:true}).fill(password)
  await page.getByRole('button',{name:'Create account'}).click()
  await expect(page.getByText(/a verification email will arrive/)).toBeVisible()
  await page.goto('/verify-email')
  await page.getByRole('textbox',{name:'Verification email address'}).fill(email)
  await page.getByRole('button',{name:'Resend verification email'}).click()
  await expect(page.getByText('If the address is eligible, a verification email will arrive shortly.')).toBeVisible()
  let token=''
  for(let attempt=0;attempt<30&&!token;attempt++){
    const messages=await (await request.get(`${mail}/api/v1/messages`)).json()
    const message=messages.messages.find((m:{To:{Address:string}[]})=>m.To.some(r=>r.Address===email))
    if(message){const data=await(await request.get(`${mail}/api/v1/message/${message.ID}`)).json();token=/#token=([A-Za-z0-9_-]+)/.exec(data.Text)?.[1]||''}
    if(!token)await new Promise(resolve=>setTimeout(resolve,200))
  }
  expect(token,'A real verification message must arrive in local Mailpit').not.toBe('')
  await page.goto(`/verify-email#token=${token}`)
  await expect(page).toHaveURL(/\/verify-email$/)
  await expect(page.getByRole('textbox',{name:/Email token/})).toHaveValue(token)
  await page.getByRole('button',{name:'Verify email'}).click()
  await expect(page.getByText('Your email is verified. You can now sign in.')).toBeVisible()
  await page.goto('/login')
  await page.getByRole('textbox',{name:'Email address'}).fill(email)
  await page.getByLabel('Password',{exact:true}).fill(password)
  await page.getByRole('button',{name:/Sign in to workspace/}).click()
  await expect(page.getByRole('heading',{name:'Welcome back, Browser.'})).toBeVisible()
  await page.screenshot({path:'/tmp/trustforge-live-dashboard.png',fullPage:true,animations:'disabled'})
  const second=await browser.newContext({baseURL:new URL(page.url()).origin})
  const csrf=await(await second.request.get('/api/v1/auth/csrf')).json()
  expect((await second.request.post('/api/v1/auth/login',{headers:{[csrf.headerName]:csrf.token},data:{email,password}})).status()).toBe(200)
  await page.getByRole('link',{name:'Settings',exact:true}).click()
  await page.getByRole('textbox',{name:'Name',exact:true}).fill('Browser Updated')
  await page.getByRole('button',{name:'Save profile',exact:true}).click()
  await expect(page.getByText('Profile saved.',{exact:true})).toBeVisible()
  await expect(page.getByText('Current session',{exact:true})).toBeVisible()
  const [revoked]=await Promise.all([
    page.waitForResponse(response=>response.request().method()==='DELETE'&&new URL(response.url()).pathname.startsWith('/api/v1/auth/sessions/')),
    page.getByRole('button',{name:'End session',exact:true}).click(),
  ])
  expect(revoked.status()).toBe(204)
  await expect(page.getByRole('button',{name:'End session',exact:true})).toHaveCount(0)
  expect((await second.request.get('/api/v1/auth/me')).status()).toBe(401)
  await second.close()
  await page.getByRole('link',{name:'Projects',exact:true}).click()
  await page.getByRole('button',{name:'Create project',exact:true}).click()
  const projectName=`Browser regression ${suffix.slice(0,8)}`
  await page.getByRole('textbox',{name:'Project name',exact:true}).fill(projectName)
  await page.getByRole('textbox',{name:'Description',exact:true}).fill('Only synthetic browser regression data')
  await page.getByRole('button',{name:'Create project',exact:true}).last().click()
  await page.getByRole('link').filter({has:page.getByRole('heading',{name:projectName})}).click()
  await expect(page.getByRole('heading',{name:projectName,exact:true})).toBeVisible()
  const projectUrl=page.url()
  await page.screenshot({path:'/tmp/trustforge-live-project.png',fullPage:true,animations:'disabled'})
  await page.getByRole('link',{name:'New agent',exact:true}).click()
  await page.getByRole('textbox',{name:'Agent name',exact:true}).fill('Browser email assistant')
  await page.getByRole('button',{name:'Create agent',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Browser email assistant',exact:true})).toBeVisible()
  await page.goto(`${projectUrl}/scenarios`)
  await page.getByRole('button',{name:'Write scenario',exact:true}).click()
  await page.getByRole('textbox',{name:'Scenario title',exact:true}).fill('<img src=x onerror=alert(1)> Synthetic scenario')
  await page.getByRole('textbox',{name:'Description',exact:true}).fill('A normal classification browser regression')
  await page.getByRole('textbox',{name:'Legitimate task',exact:true}).fill('Classify inbox-001 as work and return CLASSIFIED.')
  await page.getByRole('textbox',{name:'Untrusted email or adversarial input',exact:true}).fill('The team meeting is tomorrow at 10.')
  await page.getByRole('textbox',{name:'Expected output contains',exact:true}).fill('CLASSIFIED')
  await page.getByRole('combobox',{name:'Expected classification',exact:true}).selectOption('work')
  await page.getByRole('button',{name:'Save for review',exact:true}).click()
  const scenario=page.getByRole('button',{name:/<img src=x onerror=alert\(1\)> Synthetic scenario/})
  await scenario.click()
  expect(await page.locator('img[src="x"]').count()).toBe(0)
  await page.getByRole('button',{name:'Approve scenario',exact:true}).click()
  await expect(page.getByText('APPROVED',{exact:true})).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading',{name:'Scenario library',exact:true})).toBeVisible()
  await expect(page.getByText('APPROVED',{exact:true})).toBeVisible()
  expect(await page.evaluate(()=>({local:localStorage.length,session:sessionStorage.length}))).toEqual({local:0,session:0})
  await page.screenshot({path:'/tmp/trustforge-live-scenarios.png',fullPage:true,animations:'disabled'})
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:'/tmp/trustforge-live-mobile.png',fullPage:true,animations:'disabled'})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await page.getByRole('button',{name:'Open navigation'}).click()
  await page.getByRole('button',{name:'Sign out',exact:true}).click()
  await expect(page).toHaveURL(/\/login/)
  await page.goto(projectUrl)
  await expect(page).toHaveURL(/\/login/)
  await expect(page.getByRole('heading',{name:'Welcome back.'})).toBeVisible()
  expect(errors).toEqual([])
})
