import { beforeEach, describe, expect, it, vi } from 'vitest'
beforeEach(() => { vi.resetModules() })
describe('session and CSRF API boundary', () => {
  it('obtains a synchronizer token and sends only same-origin credentials with mutations', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(new Response(JSON.stringify({ token: 'test-csrf', headerName: 'X-CSRF-TOKEN' }))).mockResolvedValueOnce(new Response(JSON.stringify({ id: 'project' })))
    vi.stubGlobal('fetch', fetcher)
    const { post } = await import('./api')
    await post('/projects', { name: 'Synthetic project' })
    expect(fetcher).toHaveBeenCalledTimes(2)
    expect(fetcher.mock.calls[0][0]).toBe('/api/v1/auth/csrf')
    const [path, options] = fetcher.mock.calls[1]
    expect(path).toBe('/api/v1/projects')
    expect(options.credentials).toBe('same-origin')
    expect(options.cache).toBe('no-store')
    expect(options.headers.get('X-CSRF-TOKEN')).toBe('test-csrf')
    expect(options.headers.get('Authorization')).toBeNull()
  })
  it('expires the client session on 401 and preserves backend problem details', async () => {
    const expired = vi.fn()
    window.addEventListener('session-expired', expired)
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue(new Response(JSON.stringify({ detail: 'Sign in to continue' }), { status: 401 })))
    const { api } = await import('./api')
    await expect(api('/projects')).rejects.toMatchObject({ status: 401, message: 'Sign in to continue' })
    expect(expired).toHaveBeenCalledTimes(1)
    window.removeEventListener('session-expired', expired)
  })
  it('discards rejected CSRF material before a later mutation', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(new Response(JSON.stringify({ token: 'old', headerName: 'X-CSRF-TOKEN' })))
      .mockResolvedValueOnce(new Response('{}', { status: 403 }))
      .mockResolvedValueOnce(new Response(JSON.stringify({ token: 'fresh', headerName: 'X-CSRF-TOKEN' })))
      .mockResolvedValueOnce(new Response(null, { status: 204 }))
    vi.stubGlobal('fetch', fetcher)
    const { post } = await import('./api')
    await expect(post('/projects')).rejects.toMatchObject({ status: 403 })
    await post('/projects')
    expect(fetcher.mock.calls[3][1].headers.get('X-CSRF-TOKEN')).toBe('fresh')
  })
  it('obtains fresh CSRF material after an authenticated session has expired', async () => {
    const fetcher=vi.fn()
      .mockResolvedValueOnce(new Response(JSON.stringify({ token:'expired-session',headerName:'X-CSRF-TOKEN' })))
      .mockResolvedValueOnce(new Response('{}',{status:401}))
      .mockResolvedValueOnce(new Response(JSON.stringify({ token:'new-session',headerName:'X-CSRF-TOKEN' })))
      .mockResolvedValueOnce(new Response('{}'))
    vi.stubGlobal('fetch',fetcher)
    const { refreshCsrf, api, post }=await import('./api')
    await refreshCsrf()
    await expect(api('/projects')).rejects.toMatchObject({status:401})
    await post('/auth/login',{email:'fixture@example.test',password:'synthetic-password-only'})
    expect(fetcher.mock.calls[3][1].headers.get('X-CSRF-TOKEN')).toBe('new-session')
  })
  it.each(['https://evil.example', '//evil.example', '/\\evil.example', '/\n/evil.example', '/login?returnTo=/projects'])('rejects unsafe post-login destination %s', async path => {
    const { safeReturnPath } = await import('./api')
    expect(safeReturnPath(path)).toBe('/dashboard')
  })
  it('preserves an authorized same-origin deep link destination', async () => {
    const { safeReturnPath } = await import('./api')
    expect(safeReturnPath('/projects/project-id?tab=agents')).toBe('/projects/project-id?tab=agents')
  })
})
